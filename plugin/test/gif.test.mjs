import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, readFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {checked} from '../scripts/lib/ffmpeg.mjs';
import {listFrames, rewriteDelays} from '../scripts/lib/gif.mjs';

test('GIF generated by ffmpeg preserves bytes except frame delays', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'motion-gif-'));
  try {
    const file = path.join(directory, 'test.gif');
    await checked([
      '-f', 'lavfi', '-i', 'testsrc=size=32x32:rate=24:duration=0.25', '-y', file,
    ]);
    const input = await readFile(file);
    const frames = listFrames(input);
    assert.equal(frames.length, 6);
    const delays = [4, 4, 5, 4, 4, 4];
    const output = rewriteDelays(input, delays);
    assert.deepEqual(listFrames(output).map(frame => frame.delay), delays);
    for (let index = 0; index < input.length; index++) {
      const isDelay = frames.some(frame =>
        index === frame.delayOffset || index === frame.delayOffset + 1);
      if (!isDelay) assert.equal(output[index], input[index]);
    }
  } finally {
    await rm(directory, {recursive: true, force: true});
  }
});
